"""Generate `release/deps/pinned-R<tag>.tsv` from the offline dependency bundle.

The offline bundle already holds one exact version of every dependency; this
turns it into a small manifest that the installer can also use when the offline
package is absent, so the online route installs *exactly those versions* instead
of whatever a mirror serves today -- and can verify every download by sha256.

    python release/deps/build_pinned_manifest.py

Run it after refreshing `release/_offline` (see
`03_dependence/offline-bundle/fetch_offline_bundle.R`), then rebuild the assets
with `python release/build_assets.py`.
"""

from __future__ import annotations

import argparse
import hashlib
import os
import sys
from datetime import datetime, timezone
from pathlib import Path

HERE = Path(__file__).resolve().parent
RELEASE = HERE.parent
REPO = RELEASE.parent

R_TAG = "4.6"
BIOC = "3.23"


def md5(path: Path) -> str:
    h = hashlib.md5()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def parse_index(text: str) -> dict[str, dict]:
    """PACKAGES -> {package: {field: value}} (continuation lines folded in)."""
    out: dict[str, dict] = {}
    for record in text.split("\n\n"):
        fields: dict[str, str] = {}
        for line in record.splitlines():
            if line.startswith((" ", "\t")) and fields:
                key = list(fields)[-1]
                fields[key] += " " + line.strip()
                continue
            if ":" not in line:
                continue
            key, value = line.split(":", 1)
            fields[key.strip()] = value.strip()
        if "Package" in fields and "Version" in fields:
            out[fields["Package"]] = fields
    return out


def dep_names(fields: dict, known: set[str]) -> list[str]:
    """Names this package needs, restricted to the set we actually ship."""
    names: list[str] = []
    for key in ("Depends", "Imports", "LinkingTo"):
        for item in (fields.get(key) or "").split(","):
            name = item.strip().split("(")[0].strip()
            if name and name in known and name not in names:
                names.append(name)
    return names


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--r-tag", default=R_TAG)
    ap.add_argument("--bioconductor", default=BIOC)
    ap.add_argument("--bundle", default=str(RELEASE / "_offline"))
    ap.add_argument("--out", default=str(HERE / f"pinned-R{R_TAG}.tsv"))
    args = ap.parse_args()

    offline = Path(args.bundle)
    contrib = offline / "r-packages" / "bin" / "windows" / "contrib" / args.r_tag
    r_installers = sorted((offline / "r").glob("R-*-win.exe"))
    if not contrib.is_dir():
        print(f"no bundled packages for R {args.r_tag} at {contrib}")
        return 1
    if not r_installers:
        print(f"no bundled R installer under {offline / 'r'}")
        return 1
    r_installer = r_installers[-1]

    index = parse_index((contrib / "PACKAGES").read_text(encoding="utf-8"))
    zips = sorted(contrib.glob("*.zip"))
    known = set(index) | {p.name.rsplit("_", 1)[0] for p in zips}
    print(f"bundle   : {contrib}")
    print(f"packages : {len(zips)} zips, {len(index)} index records")

    rows = []
    for path in zips:
        name, version = path.name[:-4].rsplit("_", 1)
        meta = index.get(name, {})
        if meta.get("Version") and meta["Version"] != version:
            print(f"version mismatch for {name}: index {meta['Version']} vs file {version}")
            return 1
        rows.append({
            "name": name,
            "version": version,
            "bytes": path.stat().st_size,
            "md5": md5(path),
            "sha256": sha256(path),
            "deps": ";".join(dep_names(meta, known)),
        })
    rows.sort(key=lambda r: r["name"])

    out = Path(args.out)
    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("# nanoamp pinned R dependency set -- do not edit by hand\n")
        fh.write("# generated by release/deps/build_pinned_manifest.py from release/_offline/\n")
        fh.write(f"# generated_at\t{datetime.now(timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ')}\n")
        fh.write(f"# r_tag\t{args.r_tag}\n")
        fh.write(f"# bioconductor\t{args.bioconductor}\n")
        fh.write(f"# r_installer\t{r_installer.name}\t{r_installer.stat().st_size}"
                 f"\t{sha256(r_installer)}\n")
        fh.write(f"# packages\t{len(rows)}\n")
        fh.write("package\tversion\tbytes\tmd5\tsha256\tdeps\n")
        for r in rows:
            fh.write("\t".join(str(r[k]) for k in
                               ("name", "version", "bytes", "md5", "sha256", "deps")) + "\n")

    print(f"wrote    : {out.relative_to(REPO)}  ({out.stat().st_size / 1024:.1f} KB)")
    print(f"R runtime: {r_installer.name}  {r_installer.stat().st_size / 1e6:.1f} MB")
    print(f"total    : {sum(r['bytes'] for r in rows) / 1e6:.1f} MB of package binaries")
    return 0


if __name__ == "__main__":
    sys.exit(main())
